from docx import Document
from docx.shared import Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH
import os
import uuid
import re

def create_ieee_paper(data, filename="IEEE_Paper.docx"):

    doc = Document()

    # IEEE Font Style
    style = doc.styles['Normal']
    font = style.font
    font.name = "Times New Roman"
    font.size = Pt(10)

    # Title
    title = doc.add_heading(data.get("title","Research Paper"), 0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    # Authors
    author = doc.add_paragraph(data.get("authors","Author Name"))
    author.alignment = WD_ALIGN_PARAGRAPH.CENTER

    # Abstract
    doc.add_heading("Abstract", level=1)
    doc.add_paragraph(data.get("abstract",""))

    # Keywords
    if "keywords" in data:
        keywords = doc.add_paragraph()
        keywords.add_run("Keywords— ").bold = True
        keywords.add_run(data.get("keywords",""))

    # Sections
    sections = data.get("sections", {})

    count = 1

    for title, content in sections.items():

        doc.add_heading(f"{count}. {title}", level=1)
        doc.add_paragraph(content)

        count += 1

    # References
    if "references" in data:

        doc.add_heading("References", level=1)

        for i, ref in enumerate(data["references"], 1):
            if ref.strip().startswith('['):
                doc.add_paragraph(ref.strip())
            else:
                doc.add_paragraph(f"[{i}] {ref.strip()}")
            
    os.makedirs("generated_papers", exist_ok=True)
    filepath = os.path.join("generated_papers", filename)

    doc.save(filepath)

    return filepath

def generate_paper_from_text(content):
    # Parse the text to create the data dict
    data = {
        "title": "AI Generated Research Paper",
        "authors": "AI Assistant System",
        "abstract": "This document contains a structured research proposal and related references generated by the artificial intelligence system.",
        "keywords": "AI, Research, Proposal, Methodology",
        "sections": {},
        "references": []
    }
    
    blocks = [b.strip() for b in content.split('\n\n') if b.strip()]
    
    for block in blocks:
        lines = block.split('\n', 1)
        if len(lines) > 1:
            title = lines[0].replace('*', '').replace('#', '').strip()
            body = lines[1].replace('*', '').strip()
            if title.endswith(':'):
                title = title[:-1]
        else:
            match = re.search(r'\*\*(.*?)\*\*(.*)', block, re.DOTALL)
            if match:
                title = match.group(1).replace(':', '').strip()
                body = match.group(2).replace('*', '').strip()
            else:
                title = "Section"
                body = block.replace('*', '').strip()

        if not body:
            continue
            
        if "RELATED RESEARCH PAPERS" in title.upper():
            refs = [r.strip() for r in body.split('\n\n') if r.strip() and not r.startswith('**')]
            data.setdefault("references", []).extend(refs)
        elif "TITLE:" in title.upper() and ("LINK:" in body.upper() or "AUTHORS:" in body.upper()):
            ref_data = {}
            for line in block.split('\n'):
                if ":" in line:
                    k, v = line.split(":", 1)
                    ref_data[k.strip().lower()] = v.strip()
            
            authors = ref_data.get('authors', 'Authors')
            title_text = ref_data.get('title', 'Title')
            year = ref_data.get('year', 'Year')
            link = ref_data.get('link', '')
            
            formatted_ref = f"{authors}, “{title_text},” {year}. [Online]. {link}"
            data.setdefault("references", []).append(formatted_ref)
        else:
            data["sections"][title.title()] = body

    # Generate the file
    filename = f"paper_{uuid.uuid4().hex}.docx"
    return create_ieee_paper(data, filename)
